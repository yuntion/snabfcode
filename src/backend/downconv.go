package backend

import (
	"fmt"
	"slices"

	"github.com/tuneinsight/lattigo/v6/core/rlwe"
	"github.com/tuneinsight/lattigo/v6/ring"
	"github.com/tuneinsight/lattigo/v6/schemes/ckks"
)

// SparseDownConverter preserves a periodic, natively sparse CKKS layout. Its
// planner must establish that no distinct logical values share a trace orbit.
// The backend rejects oversized/full layouts; it does not invent a repack.
type SparseDownConverter struct {
	from, to ckks.Parameters
	eval     *rlwe.Evaluator
	key      *rlwe.EvaluationKey
}

// NewSparseDownConverter expects an evaluation key generated by the larger
// ring's key generator from the large secret to the small secret.
func NewSparseDownConverter(from, to ckks.Parameters, key *rlwe.EvaluationKey) (*SparseDownConverter, error) {
	if from.RingType() != ring.Standard || to.RingType() != ring.Standard || from.N() <= to.N() {
		return nil, fmt.Errorf("DownConv requires a strictly smaller standard CKKS ring")
	}
	if !isPrefix(from.Q(), to.Q()) || !isPrefix(from.P(), to.P()) {
		return nil, fmt.Errorf("DownConv requires exact target Q and P prefixes")
	}
	if key == nil || key.LevelQ() < to.MaxLevel() || key.LevelQ() > from.MaxLevel() || key.LevelP() > from.MaxLevelP() {
		return nil, fmt.Errorf("missing or incompatible DownConv evaluation key levels")
	}
	return &SparseDownConverter{from: from, to: to, eval: rlwe.NewEvaluator(from, nil), key: key}, nil
}

func isPrefix(large, small []uint64) bool {
	return len(small) <= len(large) && slices.Equal(large[:len(small)], small)
}

// Convert keeps the active Q prefix and scale unchanged. Any explicit level
// drop or rescale needed for the target epoch must run before this operation.
func (c *SparseDownConverter) Convert(in *rlwe.Ciphertext) (*rlwe.Ciphertext, error) {
	if in == nil || in.MetaData == nil || in.Degree() != 1 || in.Value[0].N() != c.from.N() {
		return nil, fmt.Errorf("DownConv requires a degree-one source ciphertext")
	}
	if !in.IsBatched || in.LogDimensions.Rows != 0 || in.LogDimensions.Cols < 0 ||
		in.LogDimensions.Cols > c.to.LogMaxSlots() {
		return nil, fmt.Errorf("DownConv would merge independent slots; repack or reject the conversion")
	}
	if in.Level() > c.to.MaxLevel() {
		return nil, fmt.Errorf("target Q chain does not cover the active level; align levels explicitly")
	}
	out := ckks.NewCiphertext(c.to, 1, in.Level())
	// Lattigo key-switches to the embedded secret, then decimates the switched
	// coefficients by N/N' (the normalized trace in the standard ring).
	if err := c.eval.ApplyEvaluationKey(in, c.key, out); err != nil {
		return nil, fmt.Errorf("DownConv key switching and projection: %w", err)
	}
	return out, nil
}
